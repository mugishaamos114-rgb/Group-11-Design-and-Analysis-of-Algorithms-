"""
run_benchmark.py - Module D experiment for the report.

Times every sorting algorithm for n = 100, 500, 1,000, 2,000, 5,000 and
10,000 on random, sorted and reverse-sorted input (3 runs each, averaged),
plus n = 50,000 and 100,000 for merge sort and quicksort.  It then writes

    results/results.csv                 raw averages
    report/tables/*.tex                 LaTeX tables for the Overleaf report
    report/figures/*.pdf and *.png      charts (needs matplotlib)

Usage (from the project folder):
    python benchmark/run_benchmark.py            # full experiment (several minutes)
    python benchmark/run_benchmark.py --quick    # small sizes only, for a test run
"""

import argparse
import csv
import os
import platform
import sys
import time

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)

from backend import analysis                    # noqa: E402
from backend.sorting import ALGORITHMS, find_algorithm   # noqa: E402

KIND_TITLES = {"random": "Random input", "sorted": "Sorted input", "reverse": "Reverse-sorted input"}

# Categorical palette (validated, colour-blind safe for 3 series per chart).
COLORS = ["#2a78d6", "#eb6834", "#1baf7a"]
MARKERS = ["o", "s", "^"]


def run(quick):
    sizes = [100, 200, 500] if quick else analysis.STANDARD_SIZES + analysis.LARGE_SIZES
    keys = analysis.all_keys()
    start = time.time()

    def progress(done, total, m):
        print("[%3d/%d] %-26s %-8s n=%-7d %10.3f ms   (%.0f s elapsed)"
              % (done, total, find_algorithm(m.key).name, m.kind, m.n, m.avg_ms(), time.time() - start),
              flush=True)

    results = analysis.run_experiment(keys, analysis.INPUT_KINDS, sizes, 3, progress)
    return [results.get(i) for i in range(results.size())]


def save_csv(rows, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="") as handle:
        w = csv.writer(handle)
        w.writerow(["algorithm", "input", "n", "repeats", "avg_time_ms", "avg_comparisons",
                    "avg_swaps_or_moves", "theory", "time_over_f_n_ns"])
        for m in rows:
            label, f = analysis.theoretical(m.key, m.kind, m.n)
            w.writerow([find_algorithm(m.key).name, m.kind, m.n, m.repeats, "%.4f" % m.avg_ms(),
                        "%.0f" % m.comparisons, "%.0f" % m.moves, label, "%.4f" % (m.avg_ns / f)])


def lookup(rows, key, kind, n):
    for m in rows:
        if m.key == key and m.kind == kind and m.n == n:
            return m
    return None


def fmt_ms(x):
    if x >= 1000:
        return "%.0f" % x
    if x >= 10:
        return "%.1f" % x
    return "%.3f" % x


def save_latex_tables(rows, folder):
    """One table per input kind: rows = n, columns = algorithms, cells = ms."""
    os.makedirs(folder, exist_ok=True)
    sizes = sorted({m.n for m in rows})
    for kind in analysis.INPUT_KINDS:
        lines = [
            "% Generated by benchmark/run_benchmark.py - do not edit by hand",
            "\\begin{table}[H]", "\\centering", "\\small",
            "\\caption{Average running time in milliseconds (3 runs) on %s.}" % KIND_TITLES[kind].lower(),
            "\\label{tab:time-%s}" % kind,
            "\\begin{tabular}{r" + "r" * len(ALGORITHMS) + "}", "\\toprule",
            "$n$ & Bubble & Selection & Insertion & Merge & Quick (first) & Quick (random) \\\\",
            "\\midrule",
        ]
        for n in sizes:
            cells = []
            for info in ALGORITHMS:
                m = lookup(rows, info.key, kind, n)
                cells.append(fmt_ms(m.avg_ms()) if m else "--")
            lines.append("{:,}".format(n) + " & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
        with open(os.path.join(folder, "time_%s.tex" % kind), "w") as handle:
            handle.write("\n".join(lines) + "\n")

    # Operation counts at n = 1000 (shows the theory directly).
    lines = ["% Generated by benchmark/run_benchmark.py",
             "\\begin{table}[H]", "\\centering", "\\small",
             "\\caption{Average comparisons and swaps/moves for $n = 1{,}000$.}",
             "\\label{tab:counts}",
             "\\begin{tabular}{lrrrrrr}", "\\toprule",
             " & \\multicolumn{2}{c}{Random} & \\multicolumn{2}{c}{Sorted} & \\multicolumn{2}{c}{Reverse} \\\\",
             "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
             "Algorithm & Comp. & Sw./Mv. & Comp. & Sw./Mv. & Comp. & Sw./Mv. \\\\", "\\midrule"]
    for info in ALGORITHMS:
        cells = []
        for kind in analysis.INPUT_KINDS:
            m = lookup(rows, info.key, kind, 1000)
            cells += ["{:,.0f}".format(m.comparisons), "{:,.0f}".format(m.moves)] if m else ["--", "--"]
        lines.append(info.name + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(os.path.join(folder, "counts_1000.tex"), "w") as handle:
        handle.write("\n".join(lines) + "\n")

    # Ratio table: time / f(n) for random input (should be roughly constant).
    lines = ["% Generated by benchmark/run_benchmark.py",
             "\\begin{table}[H]", "\\centering", "\\small",
             "\\caption{Measured time divided by the theoretical growth $f(n)$ on random input "
             "(nanoseconds). A roughly constant column means the measurements follow the theory.}",
             "\\label{tab:ratio}",
             "\\begin{tabular}{r" + "r" * len(ALGORITHMS) + "}", "\\toprule",
             "$n$ & \\multicolumn{3}{c}{time$/n^2$} & \\multicolumn{3}{c}{time$/(n\\log_2 n)$} \\\\",
             "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
             " & Bubble & Selection & Insertion & Merge & Quick (first) & Quick (random) \\\\", "\\midrule"]
    for n in sizes:
        cells = []
        for info in ALGORITHMS:
            m = lookup(rows, info.key, "random", n)
            if m:
                _, f = analysis.theoretical(info.key, "random", n)
                cells.append("%.3f" % (m.avg_ns / f))
            else:
                cells.append("--")
        lines.append("{:,}".format(n) + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(os.path.join(folder, "ratio_random.tex"), "w") as handle:
        handle.write("\n".join(lines) + "\n")


def n_label(v, _=None):
    """Axis label: 2,000 -> '2k', 100,000 -> '100k'."""
    return "%gk" % (v / 1000) if v >= 1000 else "%g" % v


def load_csv(path):
    """Re-read results.csv (used by --charts-only)."""
    names = {a.name: a.key for a in ALGORITHMS}
    rows = []
    with open(path) as handle:
        for r in csv.DictReader(handle):
            rows.append(analysis.Measurement(names[r["algorithm"]], r["input"], int(r["n"]), int(r["repeats"]),
                                             float(r["avg_time_ms"]) * 1e6, float(r["avg_comparisons"]),
                                             float(r["avg_swaps_or_moves"])))
    return rows


def save_charts(rows, folder):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib is not installed - skipping charts (pip install matplotlib).")
        return
    os.makedirs(folder, exist_ok=True)
    plt.rcParams.update({
        "font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
        "axes.edgecolor": "#8a8984", "axes.labelcolor": "#2b2b29", "xtick.color": "#52514e",
        "ytick.color": "#52514e", "axes.grid": True, "grid.color": "#e6e5e0", "grid.linewidth": 0.6,
    })

    families = [("quadratic", "O(n²) sorts: bubble, selection, insertion"),
                ("nlogn", "O(n log n) sorts: merge sort and quicksort")]
    for family, title in families:
        infos = [a for a in ALGORITHMS if a.family == family]
        fig, axes = plt.subplots(1, 3, figsize=(10, 3.3), sharey=False)
        for ax, kind in zip(axes, analysis.INPUT_KINDS):
            for idx, info in enumerate(infos):
                pts = sorted([(m.n, m.avg_ms()) for m in rows if m.key == info.key and m.kind == kind])
                if not pts:
                    continue
                xs, ys = zip(*pts)
                ax.plot(xs, ys, color=COLORS[idx], marker=MARKERS[idx], markersize=4,
                        linewidth=2, label=info.name)
            ax.set_title(KIND_TITLES[kind], fontsize=9.5, color="#0b0b0b")
            ax.set_xlabel("n (number of elements)")
            ax.ticklabel_format(axis="x", style="plain")
            ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(n_label))
        axes[0].set_ylabel("Average time (ms)")
        handles, labels = axes[0].get_legend_handles_labels()
        fig.legend(handles, labels, loc="upper center", ncol=3, frameon=False, bbox_to_anchor=(0.5, 1.02))
        fig.suptitle(title, y=1.09, fontsize=10.5, color="#0b0b0b")
        fig.tight_layout()
        for ext in ("pdf", "png"):
            fig.savefig(os.path.join(folder, "time_%s.%s" % (family, ext)), dpi=200, bbox_inches="tight")
        plt.close(fig)

    # Measured vs fitted theory on random input (one panel per algorithm).
    fig, axes = plt.subplots(2, 3, figsize=(10, 5.6))
    for ax, info in zip(axes.flat, ALGORITHMS):
        pts = sorted([(m.n, m.avg_ns) for m in rows if m.key == info.key and m.kind == "random"])
        if not pts:
            continue
        xs = [p[0] for p in pts]
        ys = [p[1] / 1e6 for p in pts]
        fs = [analysis.theoretical(info.key, "random", n)[1] for n in xs]
        # least-squares constant c for time ~ c * f(n)
        c = sum(p[1] * f for p, f in zip(pts, fs)) / sum(f * f for f in fs)
        label = analysis.theoretical(info.key, "random", xs[-1])[0]
        ax.plot(xs, ys, color=COLORS[0], marker="o", markersize=4, linewidth=2, label="measured")
        ax.plot(xs, [c * f / 1e6 for f in fs], color="#8a8984", linestyle="--", linewidth=1.5,
                label="fitted c·%s" % label)
        ax.set_title(info.name, fontsize=9.5)
        ax.set_xlabel("n")
        ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(n_label))
        ax.legend(frameon=False, fontsize=8)
    for ax in axes[:, 0]:
        ax.set_ylabel("time (ms)")
    fig.suptitle("Random input: measured time vs. fitted theoretical growth", fontsize=10.5)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(folder, "theory_fit.%s" % ext), dpi=200, bbox_inches="tight")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--quick", action="store_true", help="small sizes only (test run)")
    parser.add_argument("--charts-only", action="store_true",
                        help="redraw tables and charts from results/results.csv without re-timing")
    args = parser.parse_args()
    if args.charts_only:
        rows = load_csv(os.path.join(ROOT, "results", "results.csv"))
        save_latex_tables(rows, os.path.join(ROOT, "report", "tables"))
        save_charts(rows, os.path.join(ROOT, "report", "figures"))
        print("Tables and charts redrawn.")
        return
    print("Python %s on %s (%s)" % (platform.python_version(), platform.system(), platform.processor() or platform.machine()))
    rows = run(args.quick)
    save_csv(rows, os.path.join(ROOT, "results", "results.csv"))
    save_latex_tables(rows, os.path.join(ROOT, "report", "tables"))
    save_charts(rows, os.path.join(ROOT, "report", "figures"))
    with open(os.path.join(ROOT, "results", "machine.txt"), "w") as handle:
        handle.write("Python %s, %s %s, %s\n" % (platform.python_version(), platform.system(),
                                                 platform.release(), platform.machine()))
    print("Done. Results in results/, tables in report/tables/, charts in report/figures/.")


if __name__ == "__main__":
    main()
